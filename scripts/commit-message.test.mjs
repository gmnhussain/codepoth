import assert from "node:assert/strict"
import { describe, it } from "node:test"

import { MAX_HEADER_LENGTH, validateCommitMessage } from "./commit-message.mjs"

function assertValid(message) {
  assert.deepEqual(validateCommitMessage(message), [])
}

function assertRejected(message, expectedFragment) {
  const errors = validateCommitMessage(message)
  assert.ok(
    errors.some((error) => error.includes(expectedFragment)),
    `expected an error containing "${expectedFragment}", got ${JSON.stringify(errors)}`
  )
}

describe("validateCommitMessage", () => {
  it("accepts a header with a type and subject", () => {
    assertValid("docs: add performance guide\n")
  })

  it("accepts a scope and a breaking-change marker", () => {
    assertValid("feat(content)!: rename lesson frontmatter field\n")
  })

  it("accepts a body after a blank line", () => {
    assertValid(
      "fix(web): keep progress on reload\n\nRead storage after hydration.\n"
    )
  })

  it("accepts a header of exactly the maximum length", () => {
    const header = `chore: ${"a".repeat(MAX_HEADER_LENGTH - "chore: ".length)}`
    assertValid(header)
  })

  it("rejects a header one character over the maximum length", () => {
    const header = `chore: ${"a".repeat(MAX_HEADER_LENGTH - "chore: ".length + 1)}`
    assertRejected(header, "maximum is 72")
  })

  it("rejects an unknown type", () => {
    assertRejected("update: change things", "type one of")
  })

  it("rejects a header without a subject", () => {
    assertRejected("feat:", "type one of")
  })

  it("rejects an upper-case subject", () => {
    assertRejected("docs: Add guide", "lower-case")
  })

  it("rejects a subject that ends with a period", () => {
    assertRejected("docs: add guide.", "period")
  })

  it("rejects a body without a blank line after the header", () => {
    assertRejected("docs: add guide\nbody text", "blank line")
  })

  it("rejects an empty message", () => {
    assertRejected("\n# only a comment\n", "empty")
  })

  it("ignores comment lines and everything below the scissors line", () => {
    assertValid(
      [
        "docs: add guide",
        "# Please enter the commit message",
        "# ------------------------ >8 ------------------------",
        "Not a valid line: Co-Authored-By: Claude <noreply@anthropic.com>",
      ].join("\n")
    )
  })

  it("accepts messages that git generates", () => {
    assertValid("Merge branch 'feat/lesson-page'")
    assertValid('Revert "docs: add guide"')
    assertValid("fixup! docs: add guide")
    assertValid("squash! docs: add guide")
  })

  it("accepts the merge headers that git and GitHub write", () => {
    assertValid("Merge pull request #12 from owner/feat/lesson-page")
    assertValid("Merge remote-tracking branch 'origin/main'")
    assertValid("Merge tag 'v1.0.0'")
    assertValid("Merge commit '3f2a9c1'")
    assertValid("Merge branches 'feat/map' and 'feat/quiz'")
  })

  it("rejects a hand-written header that only starts with Merge", () => {
    assertRejected("Merge everything into one", "type one of")
    assertRejected("Merged the lesson pages", "type one of")
  })

  it("accepts CRLF line endings", () => {
    assertValid("docs: add guide\r\n\r\nBody.\r\n")
  })

  it("accepts a human Co-Authored-By trailer", () => {
    assertValid(
      "docs: add guide\n\nCo-Authored-By: Jane Doe <jane@example.com>\n"
    )
  })

  it("rejects an AI Co-Authored-By trailer", () => {
    assertRejected(
      "docs: add guide\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n",
      "Co-Authored-By"
    )
  })

  it("rejects a Generated with AI line", () => {
    assertRejected(
      "docs: add guide\n\nGenerated with Claude Code\n",
      "Generated with"
    )
  })

  it("rejects a Generated with line after the robot emoji", () => {
    assertRejected(
      "docs: add guide\n\n\u{1F916} Generated with Claude Code\n",
      "Generated with"
    )
  })

  it("accepts a subject where generated by is part of the change", () => {
    assertValid("feat(ai): cache answers generated by the ai tutor")
    assertValid("fix(api): reject tokens generated by cursor pagination")
  })

  it("accepts a body sentence that mentions generated by", () => {
    assertValid(
      "fix(api): validate tokens\n\nTokens generated by cursor pagination expire.\n"
    )
  })

  it("rejects the robot emoji", () => {
    assertRejected(
      "docs: add guide\n\n\u{1F916} made by a bot\n",
      "robot emoji"
    )
  })

  it("rejects AI attribution even in a merge message", () => {
    assertRejected(
      "Merge branch 'main'\n\nCo-Authored-By: Copilot <copilot@github.com>\n",
      "Co-Authored-By"
    )
  })
})
