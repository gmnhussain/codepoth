/**
 * Commit message rules (docs/development/conventions.md §3).
 * Dependency-free so the commit-msg hook works before or without an install.
 */

/** Conventional Commits types accepted in the header. */
export const COMMIT_TYPES = [
  "build",
  "chore",
  "ci",
  "docs",
  "feat",
  "fix",
  "perf",
  "refactor",
  "revert",
  "style",
  "test",
]

/** Maximum header length, in characters. */
export const MAX_HEADER_LENGTH = 72

const HEADER_PATTERN = new RegExp(
  `^(?:${COMMIT_TYPES.join("|")})(?:\\([a-z0-9-]+\\))?!?: (?<subject>.+)$`
)

// Messages that git itself writes; they are accepted as they are.
const GIT_GENERATED_PATTERN =
  /^(?:Merge (?:branch|branches|commit|pull request|remote-tracking branch|tag) |Revert "|fixup! |squash! |amend! )/

const SCISSORS_LINE = "# ------------------------ >8 ------------------------"

const AI_TOOL_NAMES =
  "claude|anthropic|copilot|chatgpt|openai|gpt|gemini|cursor|codeium|windsurf|devin|aider"

const AI_ATTRIBUTION_PATTERNS = [
  {
    pattern: new RegExp(`^co-authored-by:.*\\b(?:${AI_TOOL_NAMES})\\b`, "im"),
    reason: "AI Co-Authored-By trailer",
  },
  {
    // Only a line that starts with the phrase (optionally after the robot emoji),
    // so subjects such as "answers generated by the ai tutor" stay valid.
    pattern: new RegExp(
      `^(?:\\u{1F916}\\s*)?generated (?:with|by)\\b.*\\b(?:${AI_TOOL_NAMES})\\b`,
      "imu"
    ),
    reason: '"Generated with …" AI attribution',
  },
  { pattern: /\u{1F916}/u, reason: "robot emoji attribution" },
]

/**
 * Removes what git strips before saving: everything from the scissors line
 * down, comment lines and trailing blank lines.
 */
export function cleanCommitMessage(rawMessage) {
  const [beforeScissors = ""] = rawMessage.split(SCISSORS_LINE)
  const lines = beforeScissors
    .replace(/\r\n/g, "\n")
    .split("\n")
    .filter((line) => !line.startsWith("#"))
    .map((line) => line.trimEnd())

  while (lines.length > 0 && lines.at(-1) === "") {
    lines.pop()
  }
  return lines
}

/** Returns every rule the message breaks; an empty array means it is valid. */
export function validateCommitMessage(rawMessage) {
  const lines = cleanCommitMessage(rawMessage)
  const header = lines[0] ?? ""
  const errors = []

  const fullMessage = lines.join("\n")
  for (const { pattern, reason } of AI_ATTRIBUTION_PATTERNS) {
    if (pattern.test(fullMessage)) {
      errors.push(`No AI attribution allowed: found ${reason}.`)
    }
  }

  if (header === "") {
    errors.push("The commit message is empty.")
    return errors
  }

  if (GIT_GENERATED_PATTERN.test(header)) {
    return errors
  }

  if (header.length > MAX_HEADER_LENGTH) {
    errors.push(
      `The header is ${header.length} characters; the maximum is ${MAX_HEADER_LENGTH}.`
    )
  }

  const subject = HEADER_PATTERN.exec(header)?.groups?.subject
  if (subject === undefined) {
    errors.push(
      `The header must be "type(scope): subject" or "type: subject", with type one of: ${COMMIT_TYPES.join(", ")}.`
    )
  } else {
    if (/^[A-Z]/.test(subject)) {
      errors.push("The subject must start with a lower-case letter.")
    }
    if (subject.endsWith(".")) {
      errors.push("The subject must not end with a period.")
    }
  }

  if (lines.length > 1 && lines[1] !== "") {
    errors.push("Leave a blank line between the header and the body.")
  }

  return errors
}
